package ca.yorku.eecs3311.orion.util;

import ca.yorku.eecs3311.orion.model.ThreatAdvisory;

import java.io.FileWriter;
import java.io.IOException;
import java.util.List;

/**
 * Utility class for exporting threat advisories into formatted Markdown or text briefings.
 * Fulfills Feature F07 (Executive Threat Intelligence Report Export).
 */
public class ReportExporter {

    /**
     * Compiles a list of threat advisories into a structured Markdown briefing document
     * and writes it securely to the local filesystem.
     * 
     * @param advisories The list of threat advisories to include in the briefing.
     * @param filePath The destination file path on the local disk.
     * @return true if the export was successful, false otherwise.
     */
    /*@ 
      @ requires advisories != null && filePath != null;
      @ ensures \result == true || \result == false;
      @*/
    public boolean exportToMarkdown(List<ThreatAdvisory> advisories, String filePath) {
        StringBuilder sb = new StringBuilder();
        
        sb.append("# Orion Threat Intelligence - Executive Briefing\n");
        sb.append("==================================================\n\n");
        sb.append("Generated by: Orion Autonomous Agent System\n");
        sb.append("Total Advisories Included: ").append(advisories.size()).append("\n\n");
        sb.append("---\n\n");

        for (ThreatAdvisory advisory : advisories) {
            sb.append("## Vulnerability: ").append(advisory.getId()).append("\n");
            sb.append("- **Title:** ").append(advisory.getTitle()).append("\n");
            sb.append("- **Severity Base:** ").append(advisory.getSeverity()).append("\n");
            sb.append("- **Description:**\n  > ").append(advisory.getDescription()).append("\n\n");
            sb.append("---\n\n");
        }

        try (FileWriter writer = new FileWriter(filePath)) {
            writer.write(sb.toString());
            System.out.println("Successfully exported threat briefing to: " + filePath);
            return true;
        } catch (IOException e) {
            System.err.println("I/O Error: Insufficient permissions or invalid path -> " + e.getMessage());
            return false;
        }
    }
}